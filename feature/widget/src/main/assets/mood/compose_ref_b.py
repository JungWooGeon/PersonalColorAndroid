"""B "옷걸이 벽" (4x2) Python reference composer. The Kotlin runtime must match compose_B.

  python3 compose_ref_b.py        # rebuild reference/B_*.png from the B_* assets
Order: base -> contact shadows -> garments (graded, dark rim) -> hangers -> shade -> warm light (screen)
-> grain (overlay) -> vignette -> text.  All rects are base px (1520x1056).
Slots: aspect-fit inside rect, centered horizontally; align 'top' = garment top edge on rect top (it hangs from
slot.hook = garment top-center), 'bottom' = sits on rect bottom (shoes), 'center' = centered (acc).
rot = clockwise degrees (Canvas.rotate) around the rect center.  Hanger image is drawn with its anchor on slot.hook.
Assets are generated by scratchpad vB/gen_b.py (port of the approved vB mockup generator).
"""
import json
import numpy as np
from PIL import Image, ImageDraw, ImageFilter, ImageFont
from compose_ref import HERE, MYEONG, SERIF_IT, garment, grade_garment, lum_of, hexrgb


def place(im, s):
    x, y, w, h = s['rect']; k = min(w / im.width, h / im.height)
    im = im.resize((max(1, round(im.width * k)), max(1, round(im.height * k))), Image.LANCZOS)
    oy = {'top': y, 'bottom': y + h - im.height}.get(s.get('align'), y + (h - im.height) / 2)
    big = Image.new('RGBA', (w * 3, h * 3)); big.paste(im, (round(x + (w - im.width) / 2 - x + w), round(oy - y + h)))
    if s['rot']: big = big.rotate(-s['rot'], Image.BICUBIC)
    return big, (x - w, y - h)


def rim(im, R):
    a = im.split()[3]; sh = Image.new('L', a.size); sh.paste(a, (R['dx'], R['dy']))
    r = Image.fromarray(np.clip(np.asarray(a).astype(int) - np.asarray(sh), 0, 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(R['blur']))
    hl = Image.new('RGBA', im.size, tuple(int(R['color'][i:i + 2], 16) for i in (1, 3, 5)) + (0,))
    hl.putalpha(r.point(lambda v: int(v * R['alpha']))); im.alpha_composite(hl); im.putalpha(a)
    return im


def wrap(line, f, width, brk):
    """explicit \n wins; else break after breakAfter (', '); else greedy word wrap to the rect width."""
    if '\n' in line: return line.split('\n')
    if brk in line: return [p for p in line.replace(brk, brk.rstrip() + '\n').split('\n')]
    out = ['']
    for wd in line.split(' '):
        t = (out[-1] + ' ' + wd).strip()
        if out[-1] and f.getlength(t) > width: out.append(wd)
        else: out[-1] = t
    return out


def layout_for(roles):
    return ('outer_' if 'outer' in roles else '') + ('dress' if 'dress' in roles else 'top_bottom')


def compose_B(look, wx, phase=0, line='', caption='', L=None):
    """look: {role: (garment_key, '#RRGGBB')} with roles outer/top/bottom/dress/shoes/bag/acc."""
    L = L or json.loads((HERE / 'B_layout.json').read_text())
    lay = L['layouts'][layout_for(look)]
    canvas = Image.open(HERE / f'B_{wx}_base.webp').convert('RGBA')
    light = Image.merge('RGBA', [c.resize(canvas.size, Image.BILINEAR) for c in Image.open(HERE / f'B_{wx}_light{phase}.webp').convert('RGBA').split()])
    cs, gg, R = L['contactShadow'], L['garmentGrade'][wx], L['darkRim']
    hangers = []
    for role, s in sorted(lay.items(), key=lambda kv: kv[1]['z']):
        if role not in look: continue
        key, color = look[role]
        im = grade_garment(garment(key, color), gg)
        if lum_of(color) < R['lumBelow']: im = rim(im, R)
        big, (bx, by) = place(im, s)
        m = big.split()[3].filter(ImageFilter.GaussianBlur(cs['blur'] / 2)).point(lambda v: int(v * cs['alpha']))
        shadow = Image.new('RGBA', big.size, (0, 0, 0, 0)); shadow.putalpha(m)
        canvas.alpha_composite(shadow, (bx + cs['dx'], by + cs['dy']))
        canvas.alpha_composite(big, (bx, by))
        if s.get('hanger') in L['hangers']: hangers.append(s)
    for s in hangers:  # hangers over the garments (the clips bite the waistband, the neck peeks over the collar)
        hg = L['hangers'][s['hanger']]; him = Image.open(HERE / hg['file']).convert('RGBA')
        canvas.alpha_composite(grade_garment(him, gg), (s['hook'][0] - hg['anchor'][0], s['hook'][1] - hg['anchor'][1]))
    img = np.asarray(canvas.convert('RGB')).astype(np.float32) / 255
    lt = np.asarray(light).astype(np.float32) / 255
    img = img * (1 - L['shadeMax'][wx] * lt[..., 3:4])
    img = 1 - (1 - img) * (1 - L['lightMax'][wx] * lt[..., :3])
    hh, ww = img.shape[:2]
    gr = np.asarray(Image.open(HERE / 'grain.webp').convert('L')).astype(np.float32) / 255
    g = np.tile(gr, (hh // 256 + 1, ww // 256 + 1))[:hh, :ww, None]
    ov = np.where(img < .5, 2 * img * g, 1 - 2 * (1 - img) * (1 - g))
    img = img + (ov - img) * L['grainAlpha']
    yy, xx = np.mgrid[0:hh, 0:ww]
    d = np.hypot(xx - ww / 2, yy - hh / 2) / np.hypot(ww / 2, hh / 2)
    img = img * (1 - L['vignette'] * np.clip((d - .45) / .55, 0, 1))[..., None]
    out = Image.fromarray((np.clip(img, 0, 1) * 255 + .5).astype(np.uint8))
    dr = ImageDraw.Draw(out); T = L['text']
    col = lambda spec: tuple(int(spec['color'][wx][i:i + 2], 16) for i in (1, 3, 5))
    if line:
        f = ImageFont.truetype(str(MYEONG), T['line']['size']); x, y = T['line']['rect'][:2]
        lines = wrap(line, f, T['line']['rect'][2], T['line']['breakAfter'])
        for i, ln in enumerate(lines):
            dr.text((x, y + i * T['line']['size'] * T['line']['lineSpacing']), ln, font=f, fill=col(T['line']), anchor='la')
    if caption:
        f = ImageFont.truetype(SERIF_IT[0], T['caption']['size'], index=SERIF_IT[1])
        dr.text(tuple(T['caption']['rect'][:2]), caption, font=f, fill=col(T['caption']), anchor='la')
    return out


