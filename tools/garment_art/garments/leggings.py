from kit.art_kit import *

def leggings(color):
    """High-rise flared leggings with a V crossover waistband and soft performance-knit sheen."""
    W, H = 300, 520
    pts = [(92, 14, 'c'), (208, 14, 'c'), (210, 76, 'c'), (216, 140), (212, 230), (200, 330), (198, 390), (210, 460), (222, 506, 'c'), (186, 510), (160, 506, 'c'),
           (162, 450), (160, 380), (156, 270), (150, 196, 'c'), (144, 270), (140, 380), (138, 450), (140, 506, 'c'), (114, 510), (78, 506, 'c'), (90, 460), (102, 390), (100, 330), (88, 230), (84, 140), (90, 76, 'c')]
    base = smooth(pts)
    detail = (line('M90 76 Q150 84 210 76', '#000', .3, 2) + stitch('M91 72 Q150 80 209 72', '#000', .22, 1)
              + line('M92 16 Q120 34 150 78', '#000', .3, 1.6) + line('M208 16 Q180 34 150 78', '#000', .22, 1.4)
              + stitch('M150 82 L150 196', '#000', .2, 1, '2 2')
              + stitch('M82 504 Q110 508 138 504', '#000', .2, 1) + stitch(f'M{W-82} 504 Q{W-110} 508 {W-138} 504', '#000', .2, 1))
    shade = (K('M150 196 L144 506', .42, 6, 8) + K('M150 196 L156 506', .42, 6, 8)
             + K('M88 150 Q96 280 104 380 Q92 450 84 504', .35, 12, 12) + K(f'M{W-88} 150 Q{W-96} 280 {W-104} 380 Q{W-92} 450 {W-84} 504', .4, 12, 12)
             + K('M90 76 Q150 86 210 76', .3, 3, 5) 
             + K('M100 400 Q120 404 138 400', .12, 6, 6) + K(f'M{W-100} 400 Q{W-120} 404 {W-138} 400', .14, 6, 6))
    light = (Wt('M118 110 Q122 260 124 360 Q122 440 116 500', .3, 6, 10) + Wt(f'M{W-118} 110 Q{W-122} 260 {W-124} 360 Q{W-122} 440 {W-116} 500', .3, 6, 8)
             + Wt('M118 130 Q124 260 124 360', .2, 3, 3)
             + Wt('M100 22 Q124 40 146 70', .22, 3, 5) + Wt('M96 150 Q100 220 106 300', .14, 12, 8))
    return piece(W, H, base, color, (.18, .3), shade, light, '', detail, grain=(1.8, .15), name='leggings')
