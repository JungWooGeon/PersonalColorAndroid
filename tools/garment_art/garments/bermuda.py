from kit.art_kit import *

def bermuda(color):
    """Knee-length wide bermuda: front pleats, pressed creases, slant pockets, turned-up cuffs."""
    W, H = 300, 400
    pts = [(62, 20, 'c'), (238, 20, 'c'), (242, 46, 'c'), (252, 110), (264, 240), (272, 372, 'c'), (220, 378), (164, 374, 'c'), (158, 280), (150, 200, 'c'),
           (142, 280), (136, 374, 'c'), (80, 378), (28, 372, 'c'), (36, 240), (48, 110), (58, 46, 'c')]
    base = smooth(pts)
    cuffL = smooth([(33, 330, 'c'), (137, 334, 'c'), (136, 374, 'c'), (80, 378), (28, 372, 'c')])
    cuffR = smooth(mir([(33, 330, 'c'), (137, 334, 'c'), (136, 374, 'c'), (80, 378), (28, 372, 'c')], W))
    detail = (line('M58 46 L242 46', '#000', .3, 2) + stitch('M62 24 L238 24', '#000', .22, 1) + stitch('M60 42 L240 42', '#000', .22, 1)
              + ''.join(f'<rect x="{x-4}" y="17" width="8" height="32" rx="2" fill="#000" opacity=".25" filter="url(#b1)"/><rect x="{x-4}" y="16" width="8" height="30" rx="2" fill="{color}"/>' for x in (80, 122, 178, 220))
              + button(150, 33, 5.5, '#1f1d1b') + stitch('M160 48 L160 130 Q160 150 150 158', '#000', .3, 1.1) + line('M150 48 L150 196', '#000', .28, 1.6)
              + line('M66 48 L88 126', '#000', .32, 1.6) + line(f'M{W-66} 48 L{W-88} 126', '#000', .32, 1.6)
              + line('M106 48 Q104 64 106 82', '#000', .3, 1.4) + line('M124 48 Q122 60 124 72', '#000', .25, 1.2)
              + line(f'M{W-106} 48 Q{W-104} 64 {W-106} 82', '#000', .3, 1.4) + line(f'M{W-124} 48 Q{W-122} 60 {W-124} 72', '#000', .25, 1.2)
              + line('M106 84 L92 330', '#000', .12, 1.2) + line(f'M{W-106} 84 L{W-92} 330', '#000', .12, 1.2)
              + raised(cuffL, color, .35, .14) + raised(cuffR, color, .35, .14) + ''.join(f'<path d="{c}" fill="url(#fg)"/><path d="{c}" fill="#fff" opacity=".07"/>' for c in (cuffL, cuffR))
              + line('M34 333 L136 337', '#fff', .25, 2) + line(f'M{W-34} 333 L{W-136} 337', '#fff', .2, 2)
              + stitch('M34 336 L136 339', '#000', .25, 1) + stitch(f'M{W-34} 336 L{W-136} 339', '#000', .25, 1))
    shade = (K('M150 200 L142 372', .45, 6, 8) + K('M150 200 Q154 290 160 372', .45, 6, 8)
             + K('M46 120 Q36 250 30 370', .3, 12, 14) + K(f'M{W-46} 120 Q{W-36} 250 {W-30} 370', .35, 12, 14)
             + K('M104 52 Q110 64 108 84', .25, 3, 4) + K(f'M{W-104} 52 Q{W-110} 64 {W-108} 84', .28, 3, 4)
             + K('M34 340 L136 344', .25, 6, 6) + K(f'M{W-34} 340 L{W-136} 344', .28, 6, 6))
    light = (Wt('M108 84 L96 328', .3, 3, 4) + Wt(f'M{W-108} 84 L{W-96} 328', .22, 3, 4)
             + Wt('M76 120 Q70 230 66 320', .25, 22, 30) + Wt(f'M{W-76} 120 Q{W-70} 230 {W-66} 320', .18, 22, 26)
             + Wt('M136 206 Q116 220 96 224', .25, 3, 4) + Wt('M164 206 Q184 220 204 224', .2, 3, 4))
    return piece(W, H, base, color, (.14, .3), shade, light, '', detail, grain=(1.5, .25), name='bermuda')
