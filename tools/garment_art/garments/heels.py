    shade = (K('M28 188 Q100 186 150 170 Q210 140 278 120', .32, 6, 10) + K('M120 158 Q190 152 236 122 Q262 104 280 84', .35, 3, 6)
             + K('M240 130 Q258 140 262 190', .3, 3, 5))
