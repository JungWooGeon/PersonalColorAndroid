from kit.art_kit import *

def blazer(color):
    """오버핏 블레이저: boxy oversized blazer, dropped shoulders, long wide sleeves, deep single-button V, flap pockets."""
    W, H = 400, 440
    left = [(200, 30, 'c'), (166, 26, 'c'), (96, 42, 'c'), (74, 56), (62, 110), (52, 220), (42, 330), (34, 404, 'c'), (94, 414, 'c'),
            (98, 330), (104, 240), (116, 176, 'c'), (114, 280), (112, 360), (110, 420, 'c'), (150, 424), (200, 422, 'c')]
    base = smooth(sym(left, W))
    vopen = smooth([(170, 28, 'c'), (200, 282, 'c'), (230, 28, 'c'), (200, 36)])
    lapL = [(168, 26, 'c'), (140, 42), (126, 128, 'c'), (106, 136, 'c'), (122, 162, 'c'), (198, 286, 'c'), (176, 38, 'c')]
    collar_back = smooth([(166, 26, 'c'), (200, 20), (234, 26, 'c'), (226, 38), (200, 34), (174, 38, 'c')])
    pk = lambda x: f'M{x} 338 L{x+58} 336 L{x+58} 356 Q{x+29} 360 {x} 358 Z'
    fabric = (raised(collar_back, color, .2) + shape(vopen, '#000', .45) + K(vopen, .35, 6)
              + raised(smooth(mir(lapL, W)), color, .4, .1) + raised(smooth(lapL), color, .45, .14)
              + line('M200 286 L200 421', '#000', .35, 2) + line('M202 286 L202 421', '#fff', .08, 1)
              + line('M238 178 L280 174', '#000', .3, 2.5) + line('M238 181 L280 177', '#fff', .1, 1)
              + raised(pk(118), color, .3, .1) + raised(pk(224), color, .3, .1))
    detail = (button(212, 306, 9)
              + stitch('M131 46 Q140 120 124 132', '#000', .18, 1, '3 3') + stitch(f'M{W-131} 46 Q{W-140} 120 {W-124} 132', '#000', .18, 1, '3 3')
              + ''.join(button(80 - i * 9, 380 + i * 3, 3.2) + button(W - 80 + i * 9, 380 + i * 3, 3.2) for i in range(3))
              + stitch('M38 372 Q62 376 96 380', '#000', .2) + stitch(f'M{W-38} 372 Q{W-62} 376 {W-96} 380', '#000', .2))
    shade = (K('M114 180 Q116 300 110 416', .5, 12, 14) + K(f'M{W-114} 180 Q{W-116} 300 {W-110} 416', .55, 12, 14)
             + K('M76 70 Q64 230 46 400', .25, 12, 10) + K(f'M{W-76} 70 Q{W-64} 230 {W-46} 400', .3, 12, 10)
             + K('M58 250 Q80 262 100 254', .3, 3, 3) + K(f'M{W-58} 260 Q{W-80} 272 {W-100} 264', .3, 3, 3)
             + K('M60 296 Q78 304 98 298', .2, 3, 3)
             + K('M118 410 Q200 400 282 410', .25, 6, 10) + K('M160 180 Q172 290 150 410', .18, 22, 30))
    light = (Wt('M142 140 Q152 250 142 360', .22, 22, 40) + Wt('M70 80 Q58 220 44 360', .2, 12, 12)
             + Wt('M84 48 Q72 52 66 76', .25, 6, 8) + Wt('M58 242 Q80 252 98 246', .2, 3, 2)
             + Wt(f'M{W-150} 200 Q{W-150} 280 {W-160} 380', .1, 22, 30))
    return piece(W, H, base, color, (.18, .32), shade, light, '', detail, fabric=fabric, grain=(1.1, .5), name='blazer')
