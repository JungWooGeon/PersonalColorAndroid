def ankle_boots(color):
    W, H = 320, 310
    o = smooth([(126, 36, 'c'), (218, 28, 'c'), (216, 100), (212, 180), (224, 254, 'c'), (130, 262), (24, 280, 'c'), (8, 268), (20, 254), (62, 236), (104, 210), (122, 160), (124, 90)])
    sole = smooth([(6, 268), (8, 286, 'c'), (118, 288, 'c'), (156, 270), (178, 264, 'c'), (182, 294, 'c'), (222, 294, 'c'), (226, 250, 'c'), (130, 258), (22, 276, 'c')])
    zip_ = (line('M202 40 L203 236', '#9a9a9a', .9, 2.4) + line('M202 40 L203 236', '#fff', .5, 1, ) 
            + '<rect x="198" y="44" width="8" height="15" rx="2" fill="#C9C9C9" stroke="#777" stroke-width=".8"/><circle cx="202" cy="56" r="1.6" fill="#777"/>')
    detail = (line('M126 38 L218 30', '#000', .45, 3) + zip_
              + line('M110 214 Q160 236 222 230', '#000', .22, 1.4) + stitch('M108 220 Q160 242 220 236', '#000', .25, 1, '3 2')
              + line('M8 276 L226 252', '#fff', .2, 1.2) + line('M180 268 L222 266', '#fff', .25, 1))
    slouch = ''.join(K(f'M{x0} {y} Q170 {y + d} {x1} {y - 2}', .16, 6, 6) for x0, x1, y, d in [(126, 212, 80, 10), (124, 214, 116, -8), (124, 214, 150, 9)])
    slouch += ''.join(Wt(f'M{x0} {y + 6} Q170 {y + d + 6} {x1} {y + 4}', .16, 6, 4) for x0, x1, y, d in [(126, 212, 80, 10), (124, 214, 116, -8)])
    shade = (K('M212 40 Q220 150 222 250', .45, 12, 18) + K('M30 272 Q120 266 220 252', .3, 6, 12) + slouch
             + K('M130 40 L212 40', .35, 6, 10))
    light = (Wt('M140 48 Q146 120 142 180 Q120 220 70 238', .5, 6, 10) + Wt('M146 60 Q150 120 146 170', .7, 1, 2.5)
             + Wt('M20 262 Q40 246 70 238', .75, 1, 3) + Wt('M28 258 Q50 244 90 232', .45, 3, 6))
    return shoe_svg(W, H, 'ankle_boots', color, o, sole, detail, shade, light, back=(46, -16))
