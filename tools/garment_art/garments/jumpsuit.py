from kit.art_kit import *

def jumpsuit(color):
    """Sleeveless square-neck wide-leg jumpsuit with tie belt."""
    W, H = 320, 690
    left = [(160, 68, 'c'), (116, 68, 'c'), (116, 16, 'c'), (88, 16, 'c'), (84, 60), (72, 118, 'c'), (80, 190), (90, 250), (84, 300),
            (72, 380), (58, 520), (44, 672, 'c'), (100, 676), (152, 672, 'c'), (154, 520), (160, 392, 'c')]
    base = smooth(sym(left, W))
    belt = 'M86 236 Q160 244 234 236 L236 262 Q160 270 84 262 Z'
    loopL = smooth([(156, 246), (136, 232), (116, 234), (112, 252), (124, 266), (156, 256)])
    loopR = smooth(mir([(156, 246), (136, 232), (116, 234), (112, 252), (124, 266), (156, 256)], W))
    tailL = smooth([(154, 256), (140, 292), (128, 336, 'c'), (146, 330, 'c'), (152, 296), (162, 260)])
    tailR = smooth([(166, 256), (178, 298), (190, 348, 'c'), (206, 340, 'c'), (188, 292), (172, 256)])
    knot = 'M150 242 Q160 238 170 242 L172 262 Q160 266 148 262 Z'
    bow = lambda d, folds: raised(d, color, .55, .1) + folds
    # pleats from the waist into the wide legs
    pleats = ''.join(line(f'M{x} 266 Q{x-2} 300 {x-4} 330', '#000', .22, 1.4) + line(f'M{x+1.5} 266 Q{x-.5} 300 {x-2.5} 330', '#fff', .1, 1)
                      for x in (124, 142, W - 142, W - 124))
    fabric = pleats + (raised(belt, color, .3, .08) + K('M90 262 Q160 270 230 262', .25, 3, 3)
              + bow(tailR, K('M174 262 Q186 300 196 342', .3, 3, 3)) + bow(tailL, K('M158 262 Q146 300 136 332', .3, 3, 3))
              + bow(loopL, K('M154 252 Q132 246 116 246', .35, 3, 4) + Wt('M150 242 Q130 236 120 238', .45, 3, 4))
              + bow(loopR, K(f'M{W-154} 252 Q{W-132} 246 {W-116} 246', .35, 3, 4) + Wt(f'M{W-150} 242 Q{W-130} 236 {W-120} 238', .35, 3, 4))
              + raised(knot, color, .35, .1) + K('M150 262 L170 262', .3, 3, 3))
    detail = (line('M116 68 L204 68', '#000', .3, 1.6) + stitch('M118 74 L202 74', '#000', .22, 1, '3 2.5')
              + stitch('M92 22 L88 60 Q82 96 76 116', '#000', .2, 1, '3 2.5') + stitch(f'M{W-92} 22 L{W-88} 60 Q{W-82} 96 {W-76} 116', '#000', .2, 1, '3 2.5')
              + line('M160 266 L160 392', '#000', .28, 1.6) + line('M96 274 Q104 300 92 330', '#000', .25, 1.6)
              + line(f'M{W-96} 274 Q{W-104} 300 {W-92} 330', '#000', .25, 1.6)
              + stitch('M48 660 L150 664', '#000', .2, 1, '3 3') + stitch(f'M{W-48} 660 L{W-150} 664', '#000', .2, 1, '3 3'))
    shade = (K('M116 76 L204 76', .3, 3, 6) + K('M76 120 Q86 180 92 236', .35, 12, 12) + K(f'M{W-76} 120 Q{W-86} 180 {W-92} 236', .4, 12, 12)
             + K('M118 120 Q160 150 202 120', .15, 12, 20)
             + K('M160 392 L156 670', .45, 6, 8) + K('M160 392 Q166 520 164 672', .45, 6, 8)
             + K('M78 330 Q60 500 48 668', .3, 12, 14) + K(f'M{W-78} 330 Q{W-60} 500 {W-48} 668', .35, 12, 14)
             + K('M120 280 Q114 450 104 668', .25, 12, 6) + K(f'M{W-118} 280 Q{W-114} 450 {W-104} 668', .28, 12, 6)
             + K('M88 260 Q160 272 232 260', .3, 6, 8))
    light = (Wt('M130 90 Q124 160 128 226', .25, 22, 34) + Wt('M98 300 Q90 480 80 660', .3, 22, 30)
             + Wt(f'M{W-104} 300 Q{W-98} 480 {W-90} 660', .18, 22, 26) + Wt('M136 300 Q134 480 130 660', .18, 12, 10)
             + Wt('M102 22 L98 60', .2, 3, 6))
    return piece(W, H, base, color, (.16, .3), shade, light, '', detail, fabric=fabric, grain=(1.5, .3), name='jumpsuit')
