from kit.art_kit import *


def _buckle(x, y, w, h):
    g = '#C8B48A'
    return (f'<rect x="{x-w/2}" y="{y-h/2+1.5}" width="{w}" height="{h}" rx="2" fill="none" stroke="#000" stroke-opacity=".35" stroke-width="3.2" filter="url(#b1)"/>'
            f'<rect x="{x-w/2}" y="{y-h/2}" width="{w}" height="{h}" rx="2" fill="none" stroke="{g}" stroke-width="3"/>'
            f'<line x1="{x}" y1="{y-h/2}" x2="{x}" y2="{y+h/2}" stroke="{g}" stroke-width="2"/>'
            f'<path d="M{x-w/2+1} {y-h/2} L{x+w/2-2} {y-h/2}" stroke="#FFF3C8" stroke-width="1" opacity=".8"/>')


def trench(color):
    """트렌치코트: double-breasted, cinched waist + flared skirt, big notch lapels, gun flap, epaulettes, buckled belt."""
    W, H = 400, 640
    left = [(200, 34, 'c'), (164, 28, 'c'), (140, 38), (104, 54, 'c'), (84, 74), (70, 130), (58, 220), (46, 310), (38, 404, 'c'), (94, 412, 'c'),
            (100, 320), (108, 230), (118, 176, 'c'), (126, 250), (128, 298), (120, 400), (102, 500), (80, 606, 'c'), (140, 614), (200, 612, 'c')]
    base = smooth(sym(left, W))
    vopen = smooth([(170, 32, 'c'), (200, 200, 'c'), (230, 32, 'c'), (200, 40)])
    lapL = [(166, 30, 'c'), (140, 44), (124, 112, 'c'), (108, 118, 'c'), (126, 140, 'c'), (198, 206, 'c'), (176, 40, 'c')]
    lapR = [(234, 30, 'c'), (260, 44), (276, 112, 'c'), (292, 118, 'c'), (274, 140, 'c'), (236, 196), (232, 214, 'c'), (202, 206, 'c'), (224, 40, 'c')]
    collar_back = smooth([(164, 28, 'c'), (200, 20), (236, 28, 'c'), (228, 40), (200, 35), (172, 40, 'c')])
    gunflap = smooth([(140, 40, 'c'), (106, 56, 'c'), (100, 90), (106, 146, 'c'), (128, 162), (150, 156, 'c'), (146, 60)])
    ep = lambda s: (f'M{200+s*52} 40 L{200+s*96} 56 L{200+s*95} 70 L{200+s*50} 54 Z')
    belt = 'M126 288 Q200 296 274 288 L274 310 Q200 318 126 310 Z'
    tail = smooth([(150, 298, 'c'), (164, 298, 'c'), (164, 340), (158, 396, 'c'), (146, 392, 'c'), (146, 340)])
    cuff = lambda s: (f'M{200+s*162} 356 L{200+s*101} 364 L{200+s*101} 380 L{200+s*164} 372 Z')
    fabric = (raised(collar_back, color, .2) + shape(vopen, '#000', .45) + K(vopen, .35, 6)
              + raised(gunflap, color, .3, .1) + raised(ep(1), color, .3, .12) + raised(ep(-1), color, .3, .12)
              + raised(smooth(lapR), color, .4, .1) + raised(smooth(lapL), color, .45, .14)
              + line('M232 210 L232 290', '#000', .35, 2) + line('M232 312 Q236 460 244 610', '#000', .35, 2) + line('M234 312 Q238 460 246 610', '#fff', .08, 1)
              + raised(cuff(-1), color, .3, .1) + raised(cuff(1), color, .3, .1)
              + raised(belt, color, .4, .14) + raised(tail, color, .4, .12))
    detail = (stitch('M130 291 Q200 299 270 291', '#000', .2, 1, '3 3') + stitch('M130 307 Q200 315 270 307', '#000', .2, 1, '3 3')
              + stitch('M104 92 Q106 142 128 156 Q140 154 148 150', '#000', .14, 1, '3 3')
              + stitch('M126 140 L196 204', '#000', .14, 1, '3 3') + stitch('M274 140 L232 196', '#000', .14, 1, '3 3')
              + stitch('M88 598 Q140 606 200 604 Q260 606 312 598', '#000', .18, 1, '3 3')
              + ''.join(button(x, y, 6.5, '#2A2420') for x in (168, 252) for y in (232, 270, 344))
              + button(150, 47, 4.5, '#2A2420') + button(250, 47, 4.5, '#2A2420')
              + _buckle(170, 301, 22, 26) + _buckle(84, 368, 12, 15) + _buckle(316, 368, 12, 15))
    shade = (K('M116 180 Q122 250 124 300', .45, 12, 14) + K(f'M{W-116} 180 Q{W-122} 250 {W-124} 300', .5, 12, 14)
             + K('M86 130 Q76 270 66 400', .25, 12, 10) + K(f'M{W-86} 130 Q{W-76} 270 {W-66} 400', .3, 12, 10)
             + K('M120 320 Q200 330 280 320', .3, 6, 10)
             + K('M150 320 Q136 460 116 600', .25, 12, 12) + K('M196 330 Q194 470 186 606', .14, 12, 10)
             + K('M250 320 Q270 460 290 600', .28, 12, 14) + K('M300 420 Q314 520 326 604', .2, 12, 12)
             + K('M90 600 Q200 592 310 600', .22, 6, 10) + K('M122 282 Q200 288 278 282', .25, 6, 8))
    light = (Wt('M146 150 Q154 220 146 280', .22, 22, 36) + Wt('M70 100 Q56 220 44 330', .2, 12, 12)
             + Wt('M128 340 Q112 470 96 590', .16, 12, 18) + Wt('M216 340 Q224 470 232 600', .12, 12, 18)
             + Wt(f'M{W-150} 150 Q{W-150} 220 {W-156} 280', .1, 22, 30))
    return piece(W, H, base, color, (.18, .32), shade, light, '', detail, fabric=fabric, grain=(1.6, .3), name='trench')
