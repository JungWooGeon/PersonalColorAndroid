from kit.art_kit import *

def jacket(color):
    """크롭 자켓: short boxy cropped jacket, soft puff shoulders, small notch lapel, 2 buttons, flap pockets."""
    W, H = 400, 330
    left = [(200, 32, 'c'), (168, 28, 'c'), (110, 44, 'c'), (92, 50), (80, 72), (70, 140), (62, 220), (54, 296, 'c'), (100, 304, 'c'),
            (104, 230), (110, 170), (120, 128, 'c'), (122, 190), (120, 238, 'c'), (168, 244), (192, 238), (200, 226, 'c')]
    base = smooth(sym(left, W))
    vopen = smooth([(172, 30, 'c'), (200, 156, 'c'), (228, 30, 'c'), (200, 38)])
    lapL = [(170, 28, 'c'), (150, 40), (142, 86, 'c'), (128, 92, 'c'), (140, 108, 'c'), (198, 160, 'c'), (178, 38, 'c')]
    collar_back = smooth([(168, 28, 'c'), (200, 22), (232, 28, 'c'), (224, 38), (200, 34), (176, 38, 'c')])
    pk = lambda x: f'M{x} 188 L{x+50} 186 L{x+50} 202 Q{x+25} 206 {x} 204 Z'
    fabric = (raised(collar_back, color, .2) + shape(vopen, '#000', .45) + K(vopen, .35, 6)
              + raised(smooth(mir(lapL, W)), color, .4, .1) + raised(smooth(lapL), color, .45, .14)
              + line('M200 160 L200 226', '#000', .35, 2) + line('M202 160 L202 226', '#fff', .08, 1)
              + raised(pk(130), color, .3, .1) + raised(pk(220), color, .3, .1))
    detail = (button(212, 176, 7.5) + button(212, 208, 7.5)
              + stitch('M58 278 Q78 283 100 286', '#000', .22) + stitch(f'M{W-58} 278 Q{W-78} 283 {W-100} 286', '#000', .22)
              + stitch('M124 232 Q170 238 194 228', '#000', .18, 1, '3 3') + stitch(f'M{W-124} 232 Q{W-170} 238 {W-194} 228', '#000', .18, 1, '3 3'))
    shade = (K('M120 132 Q124 190 120 236', .5, 12, 12) + K(f'M{W-120} 132 Q{W-124} 190 {W-120} 236', .55, 12, 12)
             + K('M92 90 Q80 190 66 290', .25, 12, 10) + K(f'M{W-92} 90 Q{W-80} 190 {W-66} 290', .3, 12, 10)
             + K('M156 120 Q146 190 152 236', .22, 6, 4) + K(f'M{W-156} 120 Q{W-146} 190 {W-152} 236', .22, 6, 4)
             + K('M104 150 Q98 162 108 170', .25, 3, 3) + K(f'M{W-104} 150 Q{W-98} 162 {W-108} 170', .25, 3, 3)
             + K('M124 236 Q170 242 200 228 Q230 242 276 236', .25, 6, 8))
    light = (Wt('M146 110 Q156 170 146 226', .2, 22, 34) + Wt('M96 54 Q80 62 76 90', .35, 6, 10) + Wt(f'M{W-96} 54 Q{W-80} 62 {W-76} 90', .15, 6, 10)
             + Wt('M78 100 Q68 190 60 270', .2, 12, 10) + Wt('M162 124 Q152 190 158 236', .12, 3, 2))
    return piece(W, H, base, color, (.18, .3), shade, light, '', detail, fabric=fabric, grain=(1.1, .45), name='jacket')
