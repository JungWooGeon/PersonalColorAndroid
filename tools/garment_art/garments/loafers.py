from kit.art_kit import *

def loafers(color):
    """Slim almond-toe penny loafer: low toe box, thin sole, small stacked heel."""
    W, H = 380, 200
    o = smooth([(6, 162, 'c'), (14, 152), (40, 140), (84, 131), (128, 126), (156, 124, 'c'), (204, 134), (252, 132), (290, 118, 'c'), (300, 140), (298, 166, 'c'), (12, 168, 'c')])
    sole = smooth([(4, 160), (8, 171, 'c'), (246, 172, 'c'), (256, 172, 'c'), (260, 182, 'c'), (292, 182, 'c'), (298, 164, 'c'), (12, 165, 'c')])
    strap = 'M108 129 Q140 121 170 126 L171 137 Q140 132 108 140 Z'
    detail = (raised(strap, color, .3, .15) + '<path d="M128 129 Q140 126 152 128 L152 131.5 Q140 129.5 128 132.5 Z" fill="#000" opacity=".6"/>'
              + stitch('M20 156 Q48 138 108 130', '#000', .28, 1, '3 2') + line('M22 158 Q50 140 110 133', '#fff', .14, 1)
              + line('M8 165.5 L298 165.5', '#fff', .2, 1) + line('M260 173 L292 173', '#000', .3, 1)
              + line('M157 125 Q204 138 290 119', '#000', .55, 2.6))
    shade = K('M30 162 Q150 170 292 160', .28, 6, 10) + K('M158 128 Q204 140 288 122', .42, 6, 7)
    light = (Wt('M22 150 Q56 134 104 129', .55, 3, 4) + Wt('M276 126 Q292 138 294 158', .45, 3, 4) + Wt('M190 142 Q222 146 252 140', .2, 6, 7)
             + Wt('M40 144 Q54 138 72 135', .85, 1, 2))
    return shoe_svg(W, H, 'loafers', color, o, sole, detail, shade, light, back=(36, -22))
