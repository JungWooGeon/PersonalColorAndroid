from kit.art_kit import *

def dress(color: str) -> str:
    """A-line midi: square neck, puff sleeves, shirred bodice, gathered flared skirt."""
    W, H = 400, 640
    hem = [(200, 610, 'c'), (170, 614), (140, 606), (110, 614), (78, 606), (46, 600, 'c')]
    left = [(200, 46, 'c'), (176, 44), (160, 38, 'c'), (132, 40, 'c'), (106, 32), (84, 44), (72, 74), (78, 108, 'c'), (100, 116), (122, 108, 'c'),
            (126, 150), (132, 200), (134, 232, 'c'), (116, 330), (84, 470)] + list(reversed(hem))
    base = smooth(sym(left, W))
    sq = 'M160 40 Q180 46 200 46 Q220 46 240 40 L242 72 Q242 78 236 78 L164 78 Q158 78 158 72 Z'
    neck = shape(sq, '#000', .3)
    # puff sleeve gathers + elastic hem
    sl = ''
    for s in (1, -1):
        X = lambda x: x if s == 1 else W - x
        sl += line(f'M{X(84)} 100 Q{X(104)} 110 {X(122)} 104', '#000', .3, 2) + stitch(f'M{X(86)} 96 Q{X(104)} 104 {X(120)} 99', '#fff', .3, 1, '2 2')
        sl += line(f'M{X(128)} 42 Q{X(122)} 76 {X(124)} 106', '#000', .25, 1.5)
        for i in range(4):
            sl += K(f'M{X(124 - i*9)} {46 + i*2} Q{X(116 - i*11)} 70 {X(118 - i*9)} 100', .14, 3, 3)
            sl += Wt(f'M{X(120 - i*9)} {46 + i*2} Q{X(111 - i*11)} 70 {X(113 - i*9)} 100', .16, 3, 3)
    # shirring on bodice
    shir = ''
    for y in range(92, 228, 7):
        shir += line(f'M126 {y} Q144 {y+2} 163 {y} Q182 {y-2} 200 {y} Q219 {y+2} 237 {y} Q256 {y-2} 274 {y}', '#000', .1, 1.1)
        shir += line(f'M126 {y+3} Q144 {y+5} 163 {y+3} Q182 {y+1} 200 {y+3} Q219 {y+5} 237 {y+3} Q256 {y+1} 274 {y+3}', '#fff', .08, 1.4)
    detail = (neck + line('M158 40 L158 72 Q158 79 165 79 L235 79 Q242 79 242 72 L242 40', '#000', .28, 1.6) + Wt('M162 82 L238 82', .3, 1, 1.5) + sl
              + line('M133 232 Q200 238 267 232', '#000', .35, 2) + stitch('M134 236 Q200 242 266 236', '#fff', .25, 1, '3 2')
              + stitch('M50 594 Q80 600 110 608 Q140 600 170 608 Q200 604 230 608 Q260 600 290 608 Q320 600 350 594', '#000', .2, 1, '4 3'))
    folds_k = ''.join(K(f'M{x} 240 Q{x + (x-200)*.2} 420 {x + (x-200)*1.1} 604', .26, 6, 9) for x in (144, 166, 188, 212, 236, 258))
    folds_w = ''.join(Wt(f'M{x} 240 Q{x + (x-200)*.2} 420 {x + (x-200)*1.1} 604', .22, 6, 11) for x in (155, 177, 200, 224, 247))
    shade = (folds_k + K('M162 42 Q200 52 238 42', .35, 3, 8) + K('M164 74 L236 74', .2, 3, 4) + K('M126 140 Q130 190 134 230', .3, 6, 10) + K(f'M274 140 Q270 190 266 230', .35, 6, 10)
             + K('M118 330 Q92 470 60 600', .3, 12, 16) + K('M282 330 Q308 470 340 600', .35, 12, 16)
             + K('M136 236 Q200 246 264 236', .3, 3, 6) + K('M60 604 Q200 590 340 604', .18, 6, 10) + shir)
    light = (folds_w + Wt('M160 100 Q166 160 160 220', .2, 12, 26) + Wt('M96 54 Q84 74 88 98', .3, 6, 8) + Wt(f'M{W-100} 52 Q{W-88} 70 {W-90} 92', .15, 6, 6)
             + Wt('M150 300 Q120 440 100 580', .14, 22, 34))
    return piece(W, H, base, color, (.16, .3), shade, light, '', detail, grain=(1.4, .25), name='dress')
