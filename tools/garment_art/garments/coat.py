from kit.art_kit import *


def coat(color):
    """롱 울코트: oversized drop-shoulder wool coat, big notch lapels, soft tie belt knotted at the waist."""
    W, H = 400, 640
    left = [(200, 34, 'c'), (164, 28, 'c'), (140, 38), (90, 60, 'c'), (70, 84), (56, 140), (44, 230), (34, 320), (26, 404, 'c'), (88, 414, 'c'),
            (94, 320), (102, 230), (112, 178, 'c'), (110, 300), (104, 420), (96, 520), (88, 612, 'c'), (146, 618), (200, 616, 'c')]
    base = smooth(sym(left, W))
    vopen = smooth([(168, 32, 'c'), (200, 262, 'c'), (232, 32, 'c'), (200, 40)])
    lapL = [(166, 30, 'c'), (140, 46), (124, 128, 'c'), (106, 134, 'c'), (124, 158, 'c'), (198, 268, 'c'), (176, 40, 'c')]
    collar_back = smooth([(164, 28, 'c'), (200, 21), (236, 28, 'c'), (228, 40), (200, 35), (172, 40, 'c')])
    # soft tie belt, slightly dipping, knotted off-centre with two hanging tails
    belt = 'M108 300 Q200 312 292 300 L292 324 Q200 336 108 324 Z'
    tailA = smooth([(166, 322), (180, 324), (174, 380), (166, 446), (164, 476, 'c'), (148, 466, 'c'), (154, 400), (158, 350)])
    tailB = smooth([(178, 324), (192, 322), (204, 360), (222, 410, 'c'), (206, 420, 'c'), (190, 372), (180, 344)])
    knot = smooth([(158, 308), (172, 300), (190, 304), (196, 316), (188, 330), (170, 334), (158, 326)])
    welt = lambda x, s: f'M{x} {402 + 24 * s} L{x + 46} {402 - 4 * s} L{x + 47} {412 - 4 * s} L{x + 1} {412 + 24 * s} Z'
    fabric = (raised(collar_back, color, .2) + shape(vopen, '#000', .45) + K(vopen, .35, 6)
              + raised(smooth(mir(lapL, W)), color, .4, .1) + raised(smooth(lapL), color, .45, .14)
              + line('M200 268 L200 615', '#000', .35, 2) + line('M202 268 L202 615', '#fff', .08, 1)
              + raised(welt(124, 1), color, .25, .08) + raised(welt(230, -1), color, .25, .08)
              + raised(belt, color, .35, .12) + raised(tailB, color, .35, .1) + raised(tailA, color, .4, .12) + raised(knot, color, .45, .16))
    detail = (stitch('M112 304 Q200 316 288 304', '#000', .2, 1, '3 3') + stitch('M112 320 Q200 332 288 320', '#000', .2, 1, '3 3')
              + line('M162 310 Q178 316 192 310', '#000', .3, 1.5) + line('M164 322 Q180 316 190 326', '#000', .22, 1.2)
              + line('M96 62 Q88 100 80 140', '#000', .18, 1.5) + line(f'M{W-96} 62 Q{W-88} 100 {W-80} 140', '#000', .18, 1.5)
              + stitch('M98 64 Q91 100 84 140', '#fff', .12, 1, '3 3') + stitch(f'M{W-98} 64 Q{W-91} 100 {W-84} 140', '#fff', .12, 1, '3 3')
              + stitch('M30 384 Q58 390 90 394', '#000', .22) + stitch(f'M{W-30} 384 Q{W-58} 390 {W-90} 394', '#000', .22)
              + stitch('M124 128 L198 268', '#000', .12, 1, '3 3') + stitch(f'M{W-124} 128 L{W-198} 268', '#000', .12, 1, '3 3'))
    shade = (K('M110 180 Q112 300 104 420', .5, 12, 14) + K(f'M{W-110} 180 Q{W-112} 300 {W-104} 420', .55, 12, 14)
             + K('M86 130 Q76 270 66 400', .25, 12, 10) + K(f'M{W-86} 130 Q{W-76} 270 {W-66} 400', .3, 12, 10)
             + K('M108 336 Q200 350 292 336', .3, 6, 10)                                   # gather under the belt
             + K('M150 340 Q140 470 128 610', .22, 12, 12) + K('M236 340 Q252 470 268 610', .25, 12, 14)   # drape folds
             + K('M184 344 Q188 470 186 610', .14, 12, 10) + K('M160 330 Q172 400 166 480', .25, 6, 8)
             + K('M110 290 Q200 296 290 290', .25, 6, 8) + K('M100 606 Q200 598 300 606', .25, 6, 10) + K('M160 160 Q170 260 150 300', .16, 22, 30))
    light = (Wt('M140 120 Q150 210 140 290', .22, 22, 40) + Wt('M70 100 Q56 220 44 330', .2, 12, 12)
             + Wt('M128 360 Q118 480 110 600', .14, 12, 18) + Wt('M210 360 Q218 480 226 600', .1, 12, 18)
             + Wt(f'M{W-150} 150 Q{W-150} 220 {W-160} 290', .1, 22, 30))
    return piece(W, H, base, color, (.18, .32), shade, light, '', detail, fabric=fabric, grain=(1.1, .5), name='coat')
