from kit.art_kit import *

def shirt_dress(color: str) -> str:
    """Cinched shirt dress: neat pointed collar, button placket, balloon sleeves with cuffs, self-tie waist, flared skirt, curved shirttail hem."""
    W, H = 400, 600
    left = [(200, 40, 'c'), (170, 32, 'c'), (124, 46, 'c'), (106, 60), (92, 110), (76, 190), (62, 260), (56, 300), (62, 318, 'c'), (70, 326),
            (64, 338, 'c'), (94, 344, 'c'), (96, 324), (102, 310, 'c'), (108, 240), (116, 180), (126, 144, 'c'), (128, 200), (134, 250, 'c'),
            (114, 360), (90, 470), (74, 530, 'c'), (110, 552), (160, 566), (200, 570, 'c')]
    base = smooth(sym(left, W))
    vopen = smooth([(174, 34, 'c'), (200, 90, 'c'), (226, 34, 'c'), (200, 40)])
    stand = smooth([(170, 30, 'c'), (200, 24), (230, 30, 'c'), (226, 40), (200, 36), (174, 40, 'c')])
    colL = [(172, 30, 'c'), (158, 38), (146, 72, 'c'), (170, 76, 'c'), (198, 94, 'c'), (178, 42, 'c')]
    tie = 'M134 248 Q200 258 266 248 L266 262 Q200 272 134 262 Z'
    knotL = 'M200 258 Q184 246 174 250 Q170 260 176 270 Q188 268 200 262 Z'
    knotR = 'M200 258 Q216 246 226 250 Q230 260 224 270 Q212 268 200 262 Z'
    tails = 'M196 264 Q190 290 184 316 L192 318 Q196 292 200 270 Q204 292 210 322 L218 320 Q212 292 204 264 Z'
    pocket = 'M224 116 L256 116 L256 146 Q240 152 224 146 Z'
    fabric = (raised(stand, color, .25) + shape(vopen, '#000', .45) + K(vopen, .3, 6)
              + raised(smooth(mir(colL, W)), color, .4, .12) + raised(smooth(colL), color, .45, .16)
              + raised(pocket, color, .25, .08) + stitch('M227 120 L253 120', '#000', .25, 1, '3 2')
              + line('M200 92 L200 568', '#000', .28, 1.4) + line('M212 92 L212 568', '#000', .16, 1.2) + Wt('M206 94 L206 566', .14, 3, 6))
    cuff = lambda X: (line(f'M{X(60)} 318 Q{X(80)} 322 {X(100)} 312', '#000', .3, 1.8)
                      + stitch(f'M{X(66)} 336 Q{X(80)} 340 {X(94)} 338', '#000', .22, 1, '3 2')
                      + ''.join(K(f'M{X(64 + i*8)} 300 Q{X(66 + i*8)} 306 {X(66 + i*8)} 316', .25, 1, 1.5) for i in range(5)))
    L, R = (lambda x: x), (lambda x: W - x)
    detail = (cuff(L) + cuff(R) + ''.join(button(206, y, 4, '#EDE7DD') for y in (108, 158, 208, 300, 356, 412, 468, 524))
              + raised(tails, color, .3, .1) + raised(tie, color, .35, .15)
              + raised(knotL, color, .35, .14) + raised(knotR, color, .35, .14)
              + raised('M194 252 Q200 249 206 252 L206 268 Q200 271 194 268 Z', color, .3, .2)
              + stitch('M78 524 Q110 544 160 558 Q200 564 240 558 Q290 544 322 524', '#000', .2, 1, '4 3'))
    folds = (''.join(K(f'M{x} 268 Q{x + (x-200)*.3} 400 {x + (x-200)*.9} 556', .2, 6, 8) for x in (150, 176, 232, 254))
             + ''.join(Wt(f'M{x} 268 Q{x + (x-200)*.3} 400 {x + (x-200)*.9} 556', .18, 6, 10) for x in (162, 188, 244)))
    shade = (folds + K('M126 150 Q130 210 134 250', .4, 12, 12) + K(f'M{W-126} 150 Q{W-130} 210 {W-134} 250', .45, 12, 12)
             + K('M104 80 Q86 200 70 300', .22, 12, 10) + K(f'M{W-104} 80 Q{W-86} 200 {W-70} 300', .26, 12, 10)
             + K('M66 250 Q84 262 102 254', .2, 6, 6) + K(f'M{W-66} 250 Q{W-84} 262 {W-102} 254', .22, 6, 6)
             + K('M118 300 Q100 420 80 530', .3, 12, 14) + K(f'M{W-118} 300 Q{W-100} 420 {W-80} 530', .36, 12, 14)
             + K('M140 270 Q200 280 260 270', .16, 6, 10) + K('M80 530 Q200 580 320 530', .18, 6, 10))
    light = (Wt('M150 104 Q158 170 150 230', .2, 22, 34) + Wt('M92 110 Q78 210 66 290', .2, 12, 10)
             + Wt('M160 300 Q140 420 120 520', .12, 22, 26))
    return piece(W, H, base, color, (.16, .3), shade, light, '', detail, fabric=fabric, grain=(1.6, .3), name='shirt_dress')
