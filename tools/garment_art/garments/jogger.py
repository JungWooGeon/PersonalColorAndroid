from kit.art_kit import *

def jogger(color):
    """Wide straight sweatpants: shirred elastic waist, drawcord, soft fleece, puddled hem."""
    W, H = 300, 520
    pts = [(62, 18, 'c'), (238, 18, 'c'), (240, 58, 'c'), (252, 120), (260, 230), (266, 380), (272, 498, 'c'), (238, 506), (202, 504), (166, 508, 'c'),
           (160, 340), (150, 208, 'c'), (140, 340), (134, 508, 'c'), (98, 504), (62, 506), (28, 498, 'c'), (34, 380), (40, 230), (48, 120), (60, 58, 'c')]
    base = smooth(pts)
    cord = '#F2EFE9'
    tex = ('<rect x="60" y="18" width="180" height="40" fill="url(#rib)"/>'
           + ''.join(K(f'M{x} 20 L{x+2} 56', .25, 1, 2.2) for x in range(70, 236, 9)))
    detail = (line('M60 58 L240 58', '#000', .3, 2) + stitch('M62 61 L238 61', '#000', .22, 1)
              + ''.join(f'<circle cx="{x}" cy="46" r="4.2" fill="#C9CBCE"/><circle cx="{x}" cy="46" r="2.3" fill="#2a2a2a"/>' for x in (140, 160))
              + line('M140 46 Q132 80 128 128', '#000', .25, 5) + line('M140 46 Q132 80 128 128', cord, 1, 3.6)
              + line('M160 46 Q170 84 172 134', '#000', .25, 5) + line('M160 46 Q170 84 172 134', cord, 1, 3.6)
              + '<rect x="125" y="124" width="6" height="14" rx="2" fill="#C9CBCE"/><rect x="169" y="130" width="6" height="14" rx="2" fill="#C9CBCE"/>'
              + line('M64 62 Q78 96 78 140', '#000', .28, 1.6) + line(f'M{W-64} 62 Q{W-78} 96 {W-78} 140', '#000', .28, 1.6)
              + stitch('M150 62 L150 200', '#000', .22, 1))
    shade = (K('M150 208 L146 506', .45, 6, 10) + K('M150 208 Q154 340 158 506', .45, 6, 8)
             + K('M44 140 Q36 330 30 500', .3, 12, 16) + K(f'M{W-44} 140 Q{W-36} 330 {W-30} 500', .35, 12, 16)
             + K('M60 58 L240 58', .3, 3, 5)
             + ''.join(K(f'M{44+i*30} {500-i*4} Q{60+i*28} {470-i*6} {72+i*26} {440-i*10}', .2, 3, 4) for i in range(3))
             + ''.join(K(f'M{W-44-i*30} {500-i*4} Q{W-60-i*28} {470-i*6} {W-72-i*26} {440-i*10}', .22, 3, 4) for i in range(3))
             + K('M100 200 Q96 300 108 420', .12, 12, 10))
    light = (Wt('M92 140 Q86 300 84 470', .32, 22, 40) + Wt(f'M{W-92} 140 Q{W-86} 300 {W-84} 470', .22, 22, 36)
             + Wt('M62 24 L238 24', .2, 3, 4)
             + ''.join(Wt(f'M{52+i*30} {500-i*4} Q{68+i*28} {470-i*6} {80+i*26} {440-i*10}', .22, 3, 4) for i in range(3))
             + ''.join(Wt(f'M{W-52-i*30} {500-i*4} Q{W-68-i*28} {470-i*6} {W-80-i*26} {440-i*10}', .18, 3, 4) for i in range(3))
             + Wt('M136 214 Q118 230 98 236', .25, 3, 4) + Wt('M164 214 Q182 230 202 236', .2, 3, 4))
    return piece(W, H, base, color, (.14, .3), shade, light, tex, detail, grain=(1.1, .55), name='jogger')
