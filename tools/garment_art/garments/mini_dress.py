from kit.art_kit import *

def mini_dress(color: str) -> str:
    """Bustier mini: thin straps, sweetheart neckline with a tiny bow, corset-seam bodice, gathered flared skirt."""
    W, H = 400, 450
    hem = [(200, 424, 'c'), (176, 428), (150, 420), (124, 428), (98, 420), (72, 424), (50, 414, 'c')]
    left = [(200, 92, 'c'), (186, 78), (168, 72), (150, 80, 'c'), (147, 30, 'c'), (139, 30, 'c'), (139, 84, 'c'), (128, 92, 'c'),
            (130, 140), (136, 190, 'c'), (110, 260), (84, 340)] + list(reversed(hem))
    base = smooth(sym(left, W))
    # straps are part of the outline: inner and outer edge go up to the shoulder
    bow_l = 'M200 92 Q188 82 180 86 Q178 96 184 102 Q194 100 200 94 Z'
    bow_r = 'M200 92 Q212 82 220 86 Q222 96 216 102 Q206 100 200 94 Z'
    tails = 'M198 94 L191 116 L196 117 L200 100 L204 117 L209 116 L202 94 Z'
    bow = (raised(tails, color, .3, .1) + raised(bow_l, color, .35, .15) + raised(bow_r, color, .35, .15)
           + K('M184 94 Q192 94 198 94', .3, 1, 2) + K('M216 94 Q208 94 202 94', .3, 1, 2)
           + raised('M196 88 L204 88 L204 98 L196 98 Z', color, .3, .2))
    edge = 'M128 92 Q140 84 150 80 Q168 70 186 78 Q196 84 200 92 Q204 84 214 78 Q232 70 250 80 Q260 84 272 92'
    seams = ''.join(line(f'M{x} {y} Q{x + (x-200)*.06} 150 {x + (x-200)*.02} 190', '#000', .22, 1.3) for x, y in ((166, 76), (234, 76), (146, 86), (254, 86)))
    gathers_k = ''.join(K(f'M{x} 196 Q{x + (x-200)*.3} 300 {x + (x-200)*1.25} 418', .17, 6, 7) for x in range(142, 262, 13))
    gathers_w = ''.join(Wt(f'M{x+6} 196 Q{x + 6 + (x-194)*.3} 300 {x + 6 + (x-194)*1.25} 418', .2, 3, 6) for x in range(142, 262, 13))
    detail = (line(edge, '#000', .3, 1.6) + stitch('M132 96 Q150 86 168 80 Q186 80 200 98 Q214 80 232 80 Q250 86 268 96', '#000', .22, 1, '3 2')
              + Wt('M152 86 Q168 78 184 84', .3, 3, 3) + Wt('M216 84 Q232 78 248 86', .2, 3, 3)
              + seams + line('M135 192 Q200 198 265 192', '#000', .35, 1.8) + stitch('M136 197 Q200 203 264 197', '#fff', .25, 1, '3 2')
              + stitch('M54 408 Q76 416 98 412 Q124 420 150 412 Q176 420 200 416 Q224 420 250 412 Q276 420 302 412 Q324 416 346 408', '#000', .2, 1, '4 3') + bow)
    shade = (gathers_k + K('M130 100 Q132 150 136 190', .32, 6, 10) + K('M270 100 Q268 150 264 190', .38, 6, 10)
             + K('M112 260 Q90 340 60 416', .3, 12, 14) + K('M288 260 Q310 340 340 416', .36, 12, 14)
             + K('M138 200 Q200 210 262 200', .3, 3, 6) + K('M60 418 Q200 404 340 418', .16, 6, 10)
             + K('M140 30 L140 84', .2, 3, 4) + K('M254 30 L254 84', .25, 3, 4))
    light = (gathers_w + Wt('M162 104 Q168 150 162 184', .22, 12, 22) + Wt('M143 34 L143 80', .25, 1, 2) + Wt('M257 34 L257 80', .15, 1, 2)
             + Wt('M150 240 Q130 320 110 400', .12, 22, 30))
    return piece(W, H, base, color, (.16, .3), shade, light, '', detail, grain=(1.4, .25), name='mini_dress')
