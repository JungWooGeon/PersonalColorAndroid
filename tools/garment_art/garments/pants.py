from kit.art_kit import *

def pants(color):
    """Straight cotton pants: high rise, clean straight leg, slant pockets, pressed crease, soft cuff."""
    W, H = 300, 520
    pts = [(68, 20, 'c'), (232, 20, 'c'), (238, 70), (246, 170), (248, 330), (250, 504, 'c'), (162, 508, 'c'), (159, 330), (150, 200, 'c'),
           (141, 330), (138, 508, 'c'), (50, 504, 'c'), (52, 330), (54, 170), (62, 70)]
    base = smooth(pts)
    tex = ''
    loops = ''.join(f'<rect x="{x-3.5}" y="17" width="7" height="28" rx="2" fill="#000" opacity=".25" filter="url(#b1)"/>'
                    f'<rect x="{x-3.5}" y="16" width="7" height="27" rx="2" fill="{color}"/>'
                    f'<rect x="{x-3.5}" y="16" width="7" height="27" rx="2" fill="#fff" opacity=".08"/>' for x in (86, 124, 176, 214))
    detail = (line('M65 44 L235 44', '#000', .3, 2) + stitch('M68 24 L232 24', '#000', .22, 1) + stitch('M68 40 L232 40', '#000', .22, 1)
              + loops
              + stitch('M160 46 L160 128 Q160 146 149 156', '#000', .28, 1.1) + line('M150 46 L150 168', '#000', .3, 1.8)
              + line('M70 47 Q88 64 96 112', '#000', .32, 1.8) + line(f'M{W-70} 47 Q{W-88} 64 {W-96} 112', '#000', .32, 1.8)
              + stitch('M76 47 Q92 64 99 108', '#000', .18, 1) + stitch(f'M{W-76} 47 Q{W-92} 64 {W-99} 108', '#000', .18, 1)
              + button(150, 32, 6.5, '#2a2622') + line('M140 32 L160 32', '#000', 0, 1)
              + line('M51 478 L139 482', '#000', .28, 1.6) + line(f'M{W-51} 478 L{W-139} 482', '#000', .28, 1.6)
              + stitch('M52 492 L138 496', '#000', .18, 1) + stitch(f'M{W-52} 492 L{W-138} 496', '#000', .18, 1))
    shade = (K('M150 200 L146 505', .45, 6, 9) + K('M150 200 Q153 340 156 505', .45, 6, 7)
             + K('M56 170 Q50 330 52 500', .3, 12, 14) + K(f'M{W-56} 170 Q{W-50} 330 {W-52} 500', .36, 12, 14)
             + K('M98 116 L95 476', .22, 3, 2.5) + K(f'M{W-98} 116 L{W-95} 476', .22, 3, 2.5)
             + K('M52 460 Q96 470 139 466', .2, 6, 8) + K(f'M{W-52} 460 Q{W-96} 470 {W-139} 466', .2, 6, 8)
             + K('M70 46 L230 46', .2, 6, 6)
             + ''.join(K(f'M{70+i*3} {250+i*40} Q{96} {262+i*40} {136-i*2} {256+i*40}', .12, 6, 5) for i in range(2)))
    light = (Wt('M96 120 L94 474', .45, 3, 3) + Wt(f'M{W-96} 120 L{W-94} 474', .32, 3, 3)
             + Wt('M80 130 Q76 300 74 470', .3, 22, 30) + Wt(f'M{W-80} 130 Q{W-76} 300 {W-74} 470', .2, 22, 26)
             + Wt('M138 186 Q118 196 104 214', .2, 6, 8) + Wt('M162 186 Q182 196 196 214', .14, 6, 8))
    return piece(W, H, base, color, (.14, .3), shade, light, tex, detail, grain=(1.2, .22), name='pants')
