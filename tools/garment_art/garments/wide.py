from kit.art_kit import *

def wide(color):
    """Wide trousers: soft flowing extra-wide leg, banded waist with side shirring and a self-fabric ribbon tie."""
    W, H = 320, 520
    hemL = [(16, 504, 'c'), (52, 510), (96, 506), (148, 511, 'c')]
    pts = [(80, 16, 'c'), (240, 16, 'c'), (244, 52, 'c'), (262, 150), (284, 320), (304, 504, 'c'),
           (268, 510), (224, 506), (172, 511, 'c'), (166, 330), (160, 204, 'c'), (154, 330),
           (148, 511, 'c'), (96, 506), (52, 510), (16, 504, 'c'), (36, 320), (58, 150), (76, 52, 'c')]
    base = smooth(pts)
    shir = ''.join(line(f'M{x} 20 L{x+1} 48', '#000', .22, 1.2) + line(f'M{x+2} 20 L{x+3} 48', '#fff', .12, 1)
                   for x in list(range(84, 112, 5)) + list(range(212, 240, 5)))
    bow = ('M160 33 C144 16 118 14 120 33 C122 50 146 44 160 37 Z'
           'M160 33 C176 16 202 14 200 33 C198 50 174 44 160 37 Z')
    tails = 'M155 37 C148 62 142 86 130 112 L144 116 C152 90 158 64 162 39 Z M165 37 C172 62 180 86 192 110 L178 115 C168 90 162 64 158 39 Z'
    detail = (line('M77 50 L243 50', '#000', .3, 2) + stitch('M80 20 L240 20', '#000', .16, 1) + shir
              + line('M78 54 Q90 72 94 110', '#000', .26, 1.6) + line(f'M{W-78} 54 Q{W-90} 72 {W-94} 110', '#000', .26, 1.6)
              + raised(tails, color, .3, .1) + line('M152 60 Q148 86 140 108', '#000', .15, 1) + line('M168 60 Q173 86 182 106', '#000', .15, 1)
              + raised(bow, color, .35, .14)
              + K('M126 32 Q140 34 153 35', .3, 1, 2.5) + K('M194 32 Q180 34 167 35', .3, 1, 2.5)
              + f'<ellipse cx="160" cy="35" rx="8" ry="8.5" fill="{color}"/><ellipse cx="160" cy="35" rx="8" ry="8.5" fill="#000" opacity=".12"/>'
              + Wt('M156 31 Q160 29 164 31', .3, 1, 1.5))
    folds = [(70, 160, 40, 500), (110, 190, 92, 506), (134, 250, 128, 508)]
    shade = (K('M160 204 L154 508', .45, 6, 9) + K('M160 204 Q164 340 168 508', .45, 6, 8)
             + K('M58 150 Q40 330 22 500', .3, 12, 16) + K(f'M{W-58} 150 Q{W-40} 330 {W-22} 500', .36, 12, 16)
             + ''.join(K(f'M{a} {b} Q{(a+c)/2-4} {(b+d)/2} {c} {d}', .26, 6, 9) + K(f'M{W-a} {b} Q{W-(a+c)/2+4} {(b+d)/2} {W-c} {d}', .3, 6, 9) for a, b, c, d in folds)
             + K('M80 52 L240 52', .25, 6, 7))
    light = (''.join(Wt(f'M{a+12} {b+10} Q{(a+c)/2+8} {(b+d)/2} {c+14} {d-6}', .28, 6, 10) + Wt(f'M{W-a-12} {b+10} Q{W-(a+c)/2-8} {(b+d)/2} {W-c-14} {d-6}', .18, 6, 10) for a, b, c, d in folds)
             + Wt('M90 70 Q80 280 64 490', .2, 22, 30) + Wt('M90 24 L230 24', .14, 3, 6))
    return piece(W, H, base, color, (.16, .3), shade, light, '', detail, grain=(1.6, .2), name='wide')
