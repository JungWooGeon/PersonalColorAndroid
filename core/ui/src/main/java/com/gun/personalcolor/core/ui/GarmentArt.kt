package com.gun.personalcolor.core.ui

import android.content.Context
import android.content.res.AssetManager
import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.util.LruCache
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.toArgb

/**
 * Painted garment art (assets/garments), recolored at runtime.
 *
 * Each kind ships as `<kind>_<bucket>.webp` packed as R = color weight M, G = grey light/shade G, A = alpha
 * (all premultiplied), plus an optional `<kind>_<bucket>_d.webp` with colored hardware. Then
 * `premultiplied out = color * M + G + detail`, which matches the source SVG for any base color.
 * Bucket `d` is drawn for very dark colors (more highlight so black keeps its form), `n` for the rest.
 * Generated by the w6 export script; see ClothingIllustration for the drawing entry points.
 */
object GarmentArt {
    @Volatile private var assets: AssetManager? = null
    private var kinds: Set<String> = emptySet()

    fun init(context: Context) {
        val am = context.applicationContext.assets
        kinds = am.list(DIR).orEmpty().mapNotNullTo(HashSet()) { f -> f.removeSuffix("_n.webp").takeIf { it != f } }
        assets = am
    }

    fun has(kind: String): Boolean = assets != null && kind in kinds

    /** Width / height of the art, or null when the kind has no painted art. */
    fun aspect(kind: String): Float? = packed(kind, "n")?.let { it.width.toFloat() / it.height }

    /** The garment in [color], straight-alpha ARGB_8888 at the asset's own resolution (≈420px long side). Cached. */
    fun bitmap(kind: String, color: Color): Bitmap? {
        if (!has(kind)) return null
        val argb = color.copy(alpha = 1f).toArgb()
        val key = "$kind#$argb"
        tinted.get(key)?.let { return it }
        val r = (argb shr 16 and 0xFF) / 255f
        val g = (argb shr 8 and 0xFF) / 255f
        val b = (argb and 0xFF) / 255f
        val bucket = if (0.2126f * r + 0.7152f * g + 0.0722f * b < 0.08f) "d" else "n"
        val src = packed(kind, bucket) ?: return null
        val w = src.width
        val h = src.height
        val px = IntArray(w * h).also { src.getPixels(it, 0, w, 0, 0, w, h) }
        val det = detail(kind, bucket)?.takeIf { it.width == w && it.height == h }
            ?.let { d -> IntArray(w * h).also { d.getPixels(it, 0, w, 0, 0, w, h) } }
        for (i in px.indices) {
            val p = px[i]
            val a = p ushr 24
            if (a == 0) { px[i] = 0; continue }
            val m = (p shr 16 and 0xFF) / 255f
            val grey = (p shr 8 and 0xFF) / 255f
            var pr = r * m + grey
            var pg = g * m + grey
            var pb = b * m + grey
            if (det != null) {
                val d = det[i]
                val da = (d ushr 24) / 255f
                if (da > 0f) {
                    pr += (d shr 16 and 0xFF) / 255f * da
                    pg += (d shr 8 and 0xFF) / 255f * da
                    pb += (d and 0xFF) / 255f * da
                }
            }
            val inv = 255f / a
            px[i] = (a shl 24) or (ch(pr * inv) shl 16) or (ch(pg * inv) shl 8) or ch(pb * inv)
        }
        val out = Bitmap.createBitmap(px, w, h, Bitmap.Config.ARGB_8888)
        tinted.put(key, out)
        return out
    }

    private fun ch(v: Float) = (v * 255f + 0.5f).toInt().coerceIn(0, 255)

    private fun packed(kind: String, bucket: String): Bitmap? = load("${kind}_$bucket.webp")
    private fun detail(kind: String, bucket: String): Bitmap? = load("${kind}_${bucket}_d.webp", optional = true)

    private fun load(name: String, optional: Boolean = false): Bitmap? {
        raw.get(name)?.let { return it }
        if (name in missing) return null
        val am = assets ?: return null
        val bmp = runCatching {
            am.open("$DIR/$name").use {
                BitmapFactory.decodeStream(it, null, BitmapFactory.Options().apply { inPremultiplied = false })
            }
        }.getOrNull()
        if (bmp == null) { if (optional) missing += name; return null }
        raw.put(name, bmp)
        return bmp
    }

    private const val DIR = "garments"
    private val missing = java.util.Collections.newSetFromMap(java.util.concurrent.ConcurrentHashMap<String, Boolean>())
    private val raw = object : LruCache<String, Bitmap>(12 * 1024 * 1024) {
        override fun sizeOf(key: String, value: Bitmap) = value.byteCount
    }
    private val tinted = object : LruCache<String, Bitmap>(24 * 1024 * 1024) {
        override fun sizeOf(key: String, value: Bitmap) = value.byteCount
    }
}
